// Generates src/renderer/theme/tokens.css (the default theme's CSS variable values) from the measured
// table in docs/reference/css-variables.json (computed values read from the running original; facts,
// not source). Values are turned back into relationships where the table shows them: accent
// expressions use --accent-h/s/l, colours equal to a --color-base-NN value point at that variable, so
// the accent setting and community themes that only set base colours keep working.
// Usage: node scripts/gen-tokens.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const ref = JSON.parse(fs.readFileSync(path.join(root, "docs/reference/css-variables.json"), "utf8"));

// Set elsewhere (fonts: our own stack; state-dependent values; settings write these inline).
const SKIP = new Set(["--frame-right-space", "--frame-left-space", "--zoom-multiplier", "--font-text-size", "--font-interface", "--font-text", "--font-monospace", "--font-interface-theme", "--font-text-theme", "--font-monospace-theme", "--font-monospace-default", "--font-default", "--font-mermaid", "--font-print", "--accent-h", "--accent-s", "--accent-l"]);

function reverseAccent(v, theme) {
  const t = ref[theme];
  const h = t["--accent-h"], s = t["--accent-s"], l = t["--accent-l"];
  return v
    .split(`hsl(${h}, ${s}, ${l})`).join("hsl(var(--accent-h), var(--accent-s), var(--accent-l))")
    .split(`calc(${h} - `).join("calc(var(--accent-h) - ")
    .split(`calc(${h} + `).join("calc(var(--accent-h) + ")
    .split(`calc(${s} * `).join("calc(var(--accent-s) * ")
    .split(`calc(${l} * `).join("calc(var(--accent-l) * ")
    .split(`calc(${l} - `).join("calc(var(--accent-l) - ")
    .split(`calc(${l} + `).join("calc(var(--accent-l) + ");
}

function baseIndex(theme) {
  const m = new Map();
  for (const [k, v] of Object.entries(ref[theme])) {
    if (/^--color-base-\d+$/.test(k) && /^#[0-9a-f]{3,8}$/i.test(v) && !m.has(v.toLowerCase())) m.set(v.toLowerCase(), k);
  }
  return m;
}

function value(name, theme, bases) {
  let v = ref[theme][name];
  if (!v || v.includes("??")) return null;
  if (!/^--color-base-/.test(name) && bases.has(v.toLowerCase())) return `var(${bases.get(v.toLowerCase())})`;
  return reverseAccent(v, theme);
}

const lb = baseIndex("light"), db = baseIndex("dark");
const common = [], light = [], dark = [];
for (const name of Object.keys(ref.light)) {
  if (SKIP.has(name)) continue;
  const l = value(name, "light", lb), d = value(name, "dark", db);
  if (l === null && d === null) continue;
  if (l === d) common.push(`  ${name}: ${l};`);
  else {
    if (l !== null) light.push(`  ${name}: ${l};`);
    if (d !== null) dark.push(`  ${name}: ${d};`);
  }
}

const out = `/* Generated by app/scripts/gen-tokens.mjs from docs/reference/css-variables.json. Do not edit by hand.
   Default theme variable values (both themes). Selectors match the public structure themes override:
   body for shared values, .theme-light / .theme-dark for per-theme values. */
body {
  --accent-h: ${ref.light["--accent-h"]};
  --accent-s: ${ref.light["--accent-s"]};
  --accent-l: ${ref.light["--accent-l"]};
${common.join("\n")}
}

.theme-light {
${light.join("\n")}
}

.theme-dark {
${dark.join("\n")}
}
`;
fs.writeFileSync(path.join(root, "app/src/renderer/theme/tokens.css"), out);
console.log(`tokens.css: ${common.length} shared, ${light.length} light, ${dark.length} dark`);
